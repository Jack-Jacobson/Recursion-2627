"""Writes the newest jerryio export in Downloads into a path.

Two path sets are kept in paths.cpp:
  awp : path1..N     (array `paths`,   default auto)
  nw  : nwPath1..N   (array `nwPaths`, non-WP auto)
"""
import re
from pathlib import Path

DOWNLOADS = Path(r"C:\Users\jackj\Downloads")
ROOT = Path(__file__).resolve().parent.parent
PATHS_CPP = ROOT / "src" / "paths.cpp"
PATHS_H = ROOT / "include" / "paths.h"
PER_ROW = 5

# set name -> (array name prefix, PathRef array name, label)
SETS = {
    "awp": ("path", "paths", "AWP"),
    "nw": ("nwPath", "nwPaths", "Non-WP"),
}

BLOCK_RE = re.compile(r"Point (path|nwPath)(\d+)\[\] = \{\n(.*?)\n\};", re.S)
POINT_RE = re.compile(r"\{\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\}")


def load_paths():
    """Returns {set name: {number: body}}."""
    result = {name: {} for name in SETS}
    if not PATHS_CPP.exists():
        return result
    text = PATHS_CPP.read_text(encoding="utf-8")
    prefix_to_set = {prefix: name for name, (prefix, _, _) in SETS.items()}
    for prefix, n, body in BLOCK_RE.findall(text):
        result[prefix_to_set[prefix]][int(n)] = body
    return result


def format_points(points):
    width = max(len(p) for p in points) + 1
    rows = []
    for i in range(0, len(points), PER_ROW):
        chunk = points[i:i + PER_ROW]
        cells = [(p + ",").ljust(width + 1) for p in chunk]
        if i + PER_ROW >= len(points):
            cells[-1] = chunk[-1]
        rows.append("    " + "".join(cells).rstrip())
    return "\n".join(rows)


def write_files(all_paths):
    for name, paths in all_paths.items():
        nums = sorted(paths)
        if nums != list(range(1, len(nums) + 1)):
            raise ValueError(f"{name} paths must be numbered 1..N with no gaps, got {nums}")

    cpp = [
        "// generated by src/pathify.py - run it to update paths.",
        '#include "pursuit.h"',
        "",
    ]
    h = [
        "// generated by src/pathify.py",
        "#pragma once",
        "",
        "struct PathRef {",
        "    const Point* pts;",
        "    int          len;",
        "};",
        "",
    ]
    for name, (prefix, array, _) in SETS.items():
        nums = sorted(all_paths[name])
        for n in nums:
            cpp += [
                f"Point {prefix}{n}[] = {{",
                all_paths[name][n],
                "};",
                f"extern const int {prefix}{n}Length = sizeof({prefix}{n}) / sizeof({prefix}{n}[0]);",
                "",
            ]
        cpp.append(f"const PathRef {array}[] = {{")
        cpp += [f"    {{{prefix}{n}, {prefix}{n}Length}}," for n in nums]
        cpp += ["};", f"extern const int {array[:-1]}Count = sizeof({array}) / sizeof({array}[0]);", ""]

        for n in nums:
            h += [f"extern Point {prefix}{n}[];", f"extern const int {prefix}{n}Length;"]
        h += ["", f"extern const PathRef {array}[];", f"extern const int {array[:-1]}Count;", ""]

    PATHS_CPP.write_text("\n".join(cpp), encoding="utf-8")
    PATHS_H.write_text("\n".join(h), encoding="utf-8")


def read_export():
    files = [f for f in DOWNLOADS.iterdir() if f.is_file() and f.name.startswith("path.jerryio")]
    if not files:
        print(f"No path.jerryio* export found in {DOWNLOADS}")
        raise SystemExit(1) 
    source = max(files, key=lambda f: f.stat().st_mtime)

    points = []
    for raw_line in source.read_text(encoding="utf-8", errors="ignore").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [part.strip() for part in line.split(",")]
        if len(parts) < 2:
            continue
        try:
            x, y = float(parts[0]), float(parts[1])
        except ValueError:
            continue
        point = f"{{{x * 10.0:.1f}, {y * 10.0:.1f}}}"   # cm -> mm
        if points and points[-1] == point:
            continue
        points.append(point)

    if len(points) < 2:
        print(f"Not enough points in {source.name}")
        raise SystemExit(1)
    return source, points


def describe(body):
    pts = POINT_RE.findall(body)
    if not pts:
        return "empty"
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    return f"{len(pts):3d} pts  ({x0}, {y0}) -> ({x1}, {y1})"


def choose_set():
    names = list(SETS)
    print("Path sets:")
    for i, name in enumerate(names, 1):
        print(f"  {i}: {SETS[name][2]}")
    while True:
        choice = input(f"Which set? [1-{len(names)}, default 1 = AWP, 'q' = cancel]: ").strip().lower()
        if choice == "q":
            return None
        if not choice:
            return names[0]
        if choice.isdigit() and 1 <= int(choice) <= len(names):
            return names[int(choice) - 1]
        print(f"Enter a number from 1 to {len(names)}.")


def main():
    source, points = read_export()
    all_paths = load_paths()

    print(f"Export: {source.name} ({len(points)} points)\n")
    set_name = choose_set()
    if set_name is None:
        print("Cancelled, nothing written.")
        return
    prefix, _, label = SETS[set_name]
    paths = all_paths[set_name]

    print()
    for n in sorted(paths):
        print(f"  {n}: {prefix}{n}  {describe(paths[n])}")
    new_num = len(paths) + 1
    print(f"  {new_num}: (new path)\n")

    while True:
        choice = input(f"Which path to update? [1-{new_num}, blank = cancel]: ").strip()
        if not choice:
            print("Cancelled, nothing written.")
            return
        if choice.isdigit() and 1 <= int(choice) <= new_num:
            num = int(choice)
            break
        print(f"Enter a number from 1 to {new_num}.")

    paths[num] = format_points(points)
    write_files(all_paths)
    action = "Added" if num == new_num else "Updated"
    print(f"{action} {prefix}{num} ({label}) with {len(points)} points from {source.name}")
    if num == new_num:
        print(f"Run it with: followPath({num});")


if __name__ == "__main__":
    main()
