"""Writes the newest jerryio export in Downloads into a path."""
import re
from pathlib import Path

DOWNLOADS = Path(r"C:\Users\jackj\Downloads")
ROOT = Path(__file__).resolve().parent.parent
PATHS_CPP = ROOT / "src" / "paths.cpp"
PATHS_H = ROOT / "include" / "paths.h"
PER_ROW = 5

BLOCK_RE = re.compile(r"Point path(\d+)\[\] = \{\n(.*?)\n\};", re.S)
POINT_RE = re.compile(r"\{\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\}")


def load_paths():
    if not PATHS_CPP.exists():
        return {}
    text = PATHS_CPP.read_text(encoding="utf-8")
    return {int(n): body for n, body in BLOCK_RE.findall(text)}


def format_points(points):
    width = max(len(p) for p in points) + 1
    rows = []
    for i in range(0, len(points), PER_ROW):
        chunk = points[i:i + PER_ROW]
        cells = [(p + ",").ljust(width + 1) for p in chunk]
        if i + PER_ROW >= len(points):
            cells[-1] = chunk[-1]
        rows.append("    " + "".join(cells).rstrip())
    return "\n".join(rows)


def write_files(paths):
    nums = sorted(paths)
    if nums != list(range(1, len(nums) + 1)):
        raise ValueError(f"paths must be numbered 1..N with no gaps, got {nums}")

    cpp = [
        "// generated by src/pathify.py",
        '#include "pursuit.h"',
        "",
    ]
    for n in nums:
        cpp += [
            f"Point path{n}[] = {{",
            paths[n],
            "};",
            f"extern const int path{n}Length = sizeof(path{n}) / sizeof(path{n}[0]);",
            "",
        ]
    cpp.append("const PathRef paths[] = {")
    cpp += [f"    {{path{n}, path{n}Length}}," for n in nums]
    cpp += ["};", "extern const int pathCount = sizeof(paths) / sizeof(paths[0]);", ""]

    h = [
        "// generated by src/pathify.py",
        "#pragma once",
        "",
        "struct PathRef {",
        "    const Point* pts;",
        "    int          len;",
        "};",
        "",
    ]
    for n in nums:
        h += [f"extern Point path{n}[];", f"extern const int path{n}Length;"]
    h += [
        "",
        "extern const PathRef paths[];",
        "extern const int pathCount;",
        "",
    ]

    PATHS_CPP.write_text("\n".join(cpp), encoding="utf-8")
    PATHS_H.write_text("\n".join(h), encoding="utf-8")


def read_export():
    files = [f for f in DOWNLOADS.iterdir() if f.is_file()]
    if not files:
        print("No files in Downloads")
        raise SystemExit(1)
    source = max(files, key=lambda f: f.stat().st_mtime)

    points = []
    for raw_line in source.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [part.strip() for part in line.split(",")]
        if len(parts) < 2:
            continue
        try:
            x, y = float(parts[0]), float(parts[1])
        except ValueError:
            continue
        point = f"{{{x * 10.0:.1f}, {   y * 10.0:.1f}}}"   # cm -> mm
        if points and points[-1] == point:
            continue
        points.append(point)

    if len(points) < 2:
        print(f"Not enough points in {source.name}")
        raise SystemExit(1)
    return source, points


def describe(body):
    pts = POINT_RE.findall(body)
    if not pts:
        return "empty"
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    return f"{len(pts):3d} pts  ({x0}, {y0}) -> ({x1}, {y1})"


def main():
    source, points = read_export()
    paths = load_paths()

    print(f"Export: {source.name} ({len(points)} points)\n")
    for n in sorted(paths):
        print(f"  {n}: path{n}  {describe(paths[n])}")
    new_num = len(paths) + 1
    print(f"  {new_num}: (new path)\n")

    while True:
        choice = input(f"Which path to update? [1-{new_num}, blank = cancel]: ").strip()
        if not choice:
            print("Cancelled, nothing written.")
            return
        if choice.isdigit() and 1 <= int(choice) <= new_num:
            num = int(choice)
            break
        print(f"Enter a number from 1 to {new_num}.")

    paths[num] = format_points(points)
    write_files(paths)
    action = "Added" if num == new_num else "Updated"
    print(f"{action} path{num} with {len(points)} points from {source.name}")
    if num == new_num:
        print(f"Run it with: followPath({num});")


if __name__ == "__main__":
    main()
